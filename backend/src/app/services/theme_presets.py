DEFAULT_THEME_ID = "preset:dark"


def is_builtin_preset_id(theme_id: str) -> bool:
    return theme_id in BUILTIN_PRESETS


def get_builtin_preset(theme_id: str) -> ThemeDoc | None:
    preset = BUILTIN_PRESETS.get(theme_id)
    if preset is None:
        return None
    return preset.model_copy(deep=True)


def all_builtin_summaries() -> list[dict]:
    return [
        {
            "id": theme_id,
            "name": doc.name,
            "color_scheme": doc.color_scheme,
            "base_preset": doc.base_preset,
            "scope": "builtin",
        }
        for theme_id, doc in BUILTIN_PRESETS.items()
    ]


def fallback_theme() -> ThemeDoc:
    return get_builtin_preset(DEFAULT_THEME_ID) or ThemeDoc(
        version=1,
        name="Dark",
        base_preset="preset:dark",
        color_scheme="dark",
        tokens=deepcopy(_DARK_TOKENS),
    )
